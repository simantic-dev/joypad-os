def phases(ep, n):
    if ep != 1: return None
    if n in (1, 25, 50, 75, 90): log('poll', n)
    if 25 <= n < 50: return bytes([0, 5, 3, 0])
    if 75 <= n < 90: return bytes([1, 0, 0, 0])
    if n == 90: return bytes([0, 0, 0, 0])
    return None
